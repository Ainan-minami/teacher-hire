def extract_salary(text: str) -> Optional[str]:
    """提取薪资区间，返回 '10-15K/月' 这类标准化文本；无法提取返回原文或 None。"""
    if not text:
        return None
    t = clean_text(text)
    for pat in SALARY_PATTERNS:
        m = re.search(pat, t)
        if m:
            groups = m.groups()
            if len(groups) == 3 and groups[2] in ("K", "k", "万", "w", "W", "元"):
                unit = groups[2].upper() if groups[2].lower() == "k" else groups[2]
                return f"{groups[0]}-{groups[1]}{unit}/月"
            if len(groups) == 1:
                return f"{groups[0]}/月"
    return None


def extract_deadline(text: str) -> Optional[str]:
    """提取报名截止日期。"""
    if not text:
        return None
    for pat, _label in DEADLINE_PATTERNS:
        m = re.search(pat, text)
        if m:
            return f"{m.group(1)}-{int(m.group(2)):02d}-{int(m.group(3)):02d}"
    return None


def normalize_salary_range(text: str) -> Optional[str]:
    """兼容 '10-15K/月' / '8千-1.2万/月' 等写法，转成统一格式。"""
    if not text:
        return None
    return clean_text(text)
