def clean_text(raw: str) -> str:
    """清理空白与无关字符。"""
    if not raw:
        return ""
    return re.sub(r"\s+", " ", raw).strip()


def parse_chinese_date(text: str) -> Optional[str]:
    """把 '2025-11-13'、'2026年08月03日'、'2026/08/03' 统一为 ISO 日期。"""
    if not text:
        return None
    m = re.search(r"(20\d{2})[年/-](\d{1,2})[月/-](\d{1,2})日?", text)
    if m:
        return f"{m.group(1)}-{int(m.group(2)):02d}-{int(m.group(3)):02d}"
    return None


def extract_province(text: str) -> Optional[str]:
    """从文本中识别省份。优先全称，其次简称。"""
    if not text:
        return None
    for prov in PROVINCES:
        if prov in text:
            return prov
    # 简称匹配（避免单字误匹配，要求前后有词边界或位于开头）
    for prov, aliases in PROVINCE_ALIASES.items():
        for alias in aliases[1:]:  # 跳过与全称重复的第一项
            if len(alias) == 1 and re.search(r"(?<![一-龥])" + re.escape(alias) + r"(?=[一-龥]|$)", text):
                return prov
    return None


def extract_city(text: str, province: Optional[str] = None) -> Optional[str]:
    """从文本中识别城市。"""
    if not text:
        return None
    if province in MUNICIPALITIES:
        return province
    for city in CITIES:
        if city in text:
            return city
    return None


def province_for_city(city: str) -> Optional[str]:
    """根据城市反推省份。"""
    if not city:
        return None
    if city in MUNICIPALITIES:
        return city
    return CITY_TO_PROVINCE.get(city)


def guess_province(text: str, city: Optional[str] = None) -> Optional[str]:
    """综合省份识别：先全文匹配省名，再按城市反推。"""
    p = extract_province(text)
    if p:
        return p
    return province_for_city(city or "")


def extract_education(text: str) -> Optional[str]:
    """提取学历要求（返回最严格的一个）。"""
    if not text:
        return None
    order = ["博士", "硕士", "研究生", "本科", "大专", "专科", "中专", "高中"]
    found = []
    for level in order:
        if level in text:
            found.append(level)
    if "不限学历" in text or ("学历不限" in text):
        return "学历不限"
    if not found:
        return None
    return found[0]


def extract_subject(text: str) -> Optional[str]:
    """从标题/描述中提取学科。"""
    if not text:
        return None
    for subject, kws in SUBJECT_KEYWORDS.items():
        if subject == "其他":
            continue
        for kw in kws:
            if kw.lower() in text.lower():
                return subject
    return None


